/**
 * Server-only blockchain client for the MediMesh audit layer.
 *
 * Security boundaries enforced by this module:
 *  - Nothing here may ever be imported from a client component. The signer
 *    private key is read from a server-only env var and is never returned by any
 *    function, never logged, and never prefixed with NEXT_PUBLIC_.
 *  - Transaction hashes and block numbers come only from real receipts. This
 *    module has no code path that fabricates one.
 *  - If the local chain is unreachable, callers get a typed
 *    BlockchainUnavailableError instead of a fake success.
 */
import { ethers } from "ethers";
import fs from "fs";
import path from "path";

/** ABI as generated by Hardhat, injected at build time to avoid fs reads in prod. */
import abiJson from "./abi.generated.json";

export const LEDGER_ABI = abiJson as unknown as ethers.InterfaceAbi;

export const DEFAULT_RPC_URL = "http://127.0.0.1:8545";
export const DEFAULT_CHAIN_ID = 31337;

export interface DeploymentInfo {
  contract: { name: string; address: string; deploymentTxHash: string | null; blockNumber: number | null };
  accounts: {
    admin: string;
    pharmacies: Record<string, string>;
    delivery: Record<string, string>;
  };
  /**
   * Local demo keystore — PUBLIC Hardhat dev keys. Refused in production.
   * Present only in the manifest written by blockchain/scripts/deploy.ts.
   */
  devKeys?: {
    admin: string;
    pharmacies: Record<string, string>;
    delivery: Record<string, string>;
  };
  network: { name: string; chainId: number; rpcUrl: string };
  deployedAt: string;
}

export class BlockchainUnavailableError extends Error {
  readonly reason: "no_config" | "rpc_unreachable" | "wrong_chain" | "not_deployed";
  constructor(reason: BlockchainUnavailableError["reason"], message: string) {
    super(message);
    this.name = "BlockchainUnavailableError";
    this.reason = reason;
  }
}

export class TransactionFailedError extends Error {
  readonly txHash: string | null;
  constructor(message: string, txHash: string | null = null) {
    super(message);
    this.name = "TransactionFailedError";
    this.txHash = txHash;
  }
}

/** Receipt wait budget. A local chain settles in ms; this only bounds hangs. */
const RECEIPT_TIMEOUT_MS = 60_000;
const CONFIRMATIONS = 1;

function rpcUrl(): string {
  return process.env.BLOCKCHAIN_RPC_URL || DEFAULT_RPC_URL;
}

function expectedChainId(): number {
  const raw = process.env.BLOCKCHAIN_CHAIN_ID;
  const parsed = raw ? Number(raw) : DEFAULT_CHAIN_ID;
  return Number.isFinite(parsed) ? parsed : DEFAULT_CHAIN_ID;
}

let _provider: ethers.JsonRpcProvider | null = null;

export function getProvider(): ethers.JsonRpcProvider {
  if (!_provider) _provider = new ethers.JsonRpcProvider(rpcUrl(), {
    chainId: expectedChainId(),
    name: "medimesh-local",
  });
  return _provider;
}

/**
 * A short-lived provider with batching/caching disabled, used for reads that
 * must not be memoized (notably the transaction count).
 */
function uncachedProvider(): ethers.JsonRpcProvider {
  // A freshly constructed provider starts with an empty cache, and passing the
  // chainId explicitly skips chain detection. That is all that is needed to
  // guarantee eth_getTransactionCount is not served from a stale memo.
  return new ethers.JsonRpcProvider(rpcUrl(), {
    chainId: expectedChainId(),
    name: "medimesh-local",
  });
}

/**
 * Reads the deployment manifest written by `blockchain/scripts/deploy.ts`.
 * After a local chain restart the address changes, so this is the single
 * source of truth — no address is ever hardcoded in the application.
 */
export function loadDeployment(): DeploymentInfo | null {
  const override = process.env.MEDIMESH_LEDGER_ADDRESS;
  const manifestPath =
    process.env.MEDIMESH_DEPLOYMENT_FILE ||
    path.join(process.cwd(), "blockchain", "deployments", "local.json");

  let info: DeploymentInfo | null = null;
  try {
    if (fs.existsSync(manifestPath)) {
      info = JSON.parse(fs.readFileSync(manifestPath, "utf8")) as DeploymentInfo;
    }
  } catch {
    info = null;
  }

  if (override) {
    info = info ?? ({
      contract: { name: "MediMeshLedger", address: override, deploymentTxHash: null, blockNumber: null },
      accounts: { admin: ethers.ZeroAddress, pharmacies: {}, delivery: {} },
      network: { name: "localhost", chainId: expectedChainId(), rpcUrl: rpcUrl() },
      deployedAt: new Date(0).toISOString(),
    } as DeploymentInfo);
    info.contract = { ...info.contract, address: override };
  }

  return info && ethers.isAddress(info.contract?.address ?? "") ? info : null;
}

export function contractAddress(): string | null {
  return loadDeployment()?.contract.address ?? null;
}

/**
 * Resolves a connected signer.
 *
 * The signer is the configured local demo key. Authorization still happens
 * inside the contract: this key is only an operational convenience, never a
 * bypass of on-chain role checks.
 */
export function getSigner(): ethers.Wallet {
  const key = process.env.BLOCKCHAIN_PRIVATE_KEY;
  if (!key) {
    throw new BlockchainUnavailableError(
      "no_config",
      "BLOCKCHAIN_PRIVATE_KEY is not set. Add the local dev key to .env.local (see .env.example)."
    );
  }
  try {
    return new ethers.Wallet(key, getProvider());
  } catch {
    throw new BlockchainUnavailableError("no_config", "BLOCKCHAIN_PRIVATE_KEY is not a valid private key.");
  }
}

/**
 * Resolves a signer for a specific address.
 *
 * The contract enforces roles per address, so each pharmacy / delivery wallet
 * needs its own key. For the local demonstration those keys come from the
 * manifest's public Hardhat dev keystore. This is refused in production so a
 * real key can never be picked up from a development artifact.
 */
export function getSignerFor(address: string): ethers.Wallet {
  const dep = loadDeployment();
  const dev = dep?.devKeys;

  // A public-chain manifest has no devKeys, because a public deploy must never
  // write key material to disk. Those wallets come from MM_WALLET_KEYS instead —
  // an address-to-key map held in the environment. In a real deployment this
  // would be an HSM or a KMS signing API; the indirection is the same, the key
  // simply never sits in a JSON file next to the ABI.
  const fromEnv = envWalletFor(address);

  if (!dev && !fromEnv) {
    throw new BlockchainUnavailableError(
      "no_config",
      "No keystore found for this wallet. On a public chain set MM_WALLET_KEYS; for the local " +
        "demo re-run: cd blockchain && npm run deploy"
    );
  }
  if (dev && !fromEnv && process.env.NODE_ENV === "production" && process.env.MM_ALLOW_DEV_KEYS !== "true") {
    throw new BlockchainUnavailableError(
      "no_config",
      "Local demo dev keys are disabled in production. Configure a real signer instead."
    );
  }

  const wanted = ethers.getAddress(address);

  // Cache one Wallet per address. A Wallet tracks its own nonce, so returning a
  // fresh instance on every call would re-read the nonce and can resubmit a
  // value the node has already consumed.
  const cached = signerCache.get(wanted);
  if (cached) return cached;

  if (fromEnv) {
    const wallet = new ethers.Wallet(fromEnv, getProvider());
    signerCache.set(wanted, wallet);
    return wallet;
  }

  const candidates = [dev!.admin, ...Object.values(dev!.pharmacies), ...Object.values(dev!.delivery)];
  const key = candidates.find((k) => {
    try {
      return ethers.getAddress(new ethers.Wallet(k).address) === wanted;
    } catch {
      return false;
    }
  });
  if (!key) {
    throw new BlockchainUnavailableError(
      "no_config",
      `No local dev key is mapped to ${address}. Re-run the deploy script.`
    );
  }

  const wallet = new ethers.Wallet(key, getProvider());
  signerCache.set(wanted, wallet);
  return wallet;
}

/** Address -> Wallet cache. Cleared when the deployment manifest changes. */
const signerCache = new Map<string, ethers.Wallet>();

export function clearSignerCache(): void {
  signerCache.clear();
}

/** True when the local demo keystore is usable in this environment. */
export function devKeysAvailable(): boolean {
  return Boolean(loadDeployment()?.devKeys);
}

/**
 * Looks up a wallet key in MM_WALLET_KEYS, a JSON object of
 * `{ "<address>": "0x<private key>" }`.
 *
 * Only used on a public chain, and only ever held in the environment — never
 * written into a deployment manifest.
 */
function envWalletFor(address: string): string | null {
  const raw = process.env.MM_WALLET_KEYS;
  if (!raw) return null;
  let map: Record<string, string>;
  try {
    map = JSON.parse(raw) as Record<string, string>;
  } catch {
    return null;
  }
  const wanted = ethers.getAddress(address);
  for (const [addr, key] of Object.entries(map)) {
    if (!ethers.isAddress(addr) || ethers.getAddress(addr) !== wanted) continue;
    try {
      // Never hand back a key that does not actually belong to the address it
      // is filed under.
      if (new ethers.Wallet(key).address !== wanted) return null;
      return key;
    } catch {
      return null;
    }
  }
  return null;
}

export function getContract(signer?: ethers.Signer): ethers.Contract {
  const address = contractAddress();
  if (!address) {
    throw new BlockchainUnavailableError(
      "not_deployed",
      "MediMeshLedger address not found. Run: cd blockchain && npm run deploy"
    );
  }
  return new ethers.Contract(address, LEDGER_ABI, signer ?? getProvider());
}

export interface ChainStatus {
  configured: boolean;
  rpcReachable: boolean;
  chainId: number | null;
  expectedChainId: number;
  contractAddress: string | null;
  contractDeployed: boolean;
  ready: boolean;
  signerConfigured: boolean;
  error?: string;
}

/** Read-only health check. Never throws; reports why the chain is unusable. */
export async function getChainStatus(): Promise<ChainStatus> {
  const deployment = loadDeployment();
  const address = deployment?.contract.address ?? null;
  const base: ChainStatus = {
    configured: Boolean(deployment),
    rpcReachable: false,
    chainId: null,
    expectedChainId: expectedChainId(),
    contractAddress: address,
    contractDeployed: false,
    ready: false,
    signerConfigured: Boolean(process.env.BLOCKCHAIN_PRIVATE_KEY),
  };

  try {
    const net = await getProvider().getNetwork();
    const chainId = Number(net.chainId);
    base.rpcReachable = true;
    base.chainId = chainId;
    if (chainId !== base.expectedChainId) {
      base.error = `Connected to chain ${chainId}, expected ${base.expectedChainId}.`;
      return base;
    }
  } catch (e) {
    base.error = `RPC unreachable at ${rpcUrl()}: ${e instanceof Error ? e.message : "unknown error"}`;
    return base;
  }

  if (!address) {
    base.error = "Contract address not configured.";
    return base;
  }

  try {
    const code = await getProvider().getCode(address);
    base.contractDeployed = code !== "0x" && code !== "0x0";
    if (!base.contractDeployed) {
      base.error = `No contract code at ${address}. The local chain was likely restarted — redeploy.`;
      return base;
    }
  } catch (e) {
    base.error = e instanceof Error ? e.message : "Could not read contract code";
    return base;
  }

  base.ready = true;
  return base;
}

export interface TxResult {
  txHash: string;
  blockNumber: number | null;
  status: "confirmed";
  confirmations: number;
}

/**
 * Serializes transaction submission per sender address.
 *
 * A Wallet manages nonces optimistically, so two overlapping sends from the
 * same key can pick the same nonce and one is rejected with
 * "nonce has already been used". Chaining sends per address removes that race
 * without introducing any cross-process coordination.
 */
const sendQueues = new Map<string, Promise<unknown>>();

function enqueue<T>(address: string, task: () => Promise<T>): Promise<T> {
  const previous = sendQueues.get(address) ?? Promise.resolve();
  // Swallow the predecessor's rejection so one failure cannot poison the queue.
  const next = previous.catch(() => undefined).then(task);
  // Keep the chain alive but do not retain the resolved value.
  sendQueues.set(
    address,
    next.catch(() => undefined)
  );
  return next;
}

/**
 * Sends a contract transaction and waits for a real receipt.
 *
 * `onSubmitted` fires as soon as the transaction hash is known, so the caller
 * can persist it before waiting. That ordering is what makes the outbox
 * crash-safe: a hash is never lost, and a retry can reconcile instead of
 * re-submitting.
 *
 * A receipt with status !== 1 is a revert and raises TransactionFailedError.
 * The returned txHash always comes from the submitted transaction.
 */
export async function sendTx(
  contract: ethers.Contract,
  method: string,
  args: unknown[],
  options: { from?: string; onSubmitted?: (txHash: string) => Promise<void> | void } = {}
): Promise<TxResult> {
  const from = options.from ?? (await contract.getAddress());
  return enqueue(from.toLowerCase(), () => submitAndConfirm(contract, method, args, options));
}

async function submitAndConfirm(
  contract: ethers.Contract,
  method: string,
  args: unknown[],
  options: { from?: string; onSubmitted?: (txHash: string) => Promise<void> | void }
): Promise<TxResult> {
  let response: ethers.TransactionResponse;
  try {
    // Populate first, force the sender, then send exactly once.
    const fn = contract.getFunction(method);
    const data = (await fn.populateTransaction(...args)).data;
    const signer = contract.runner as ethers.Signer;

    // Read the nonce from the node at send time rather than trusting the
    // Wallet's in-memory counter, which can drift from the chain after a
    // revert or a server restart and cause "nonce has already been used".
    //
    // A dedicated uncached provider is used because the shared JsonRpcProvider
    // memoizes eth_getTransactionCount and would hand back a stale nonce.
    // Safe because sends are serialized per address by sendQueues.
    let nonce: number | undefined;
    try {
      nonce = Number(
        await uncachedProvider().send("eth_getTransactionCount", [
          await signer.getAddress(),
          "pending",
        ])
      );
    } catch {
      nonce = undefined; // fall back to the signer's own management
    }

    response = await signer.sendTransaction({
      to: await contract.getAddress(),
      data,
      ...(options.from ? { from: options.from } : {}),
      ...(nonce != null ? { nonce } : {}),
    });
  } catch (e) {
    // A revert at estimateGas/send time still has a real error we can surface.
    throw new TransactionFailedError(describeError(e), extractHash(e));
  }

  if (options.onSubmitted) {
    try {
      await options.onSubmitted(response.hash);
    } catch (e) {
      // Persisting the hash failed, but the transaction is already live.
      // Surface it as uncertain so reconciliation picks it up.
      throw new TransactionFailedError(
        `Transaction ${response.hash} was submitted but recording its hash failed. Reconcile before retrying. (${
          e instanceof Error ? e.message : "unknown"
        })`,
        response.hash
      );
    }
  }

  let receipt: ethers.TransactionReceipt | null = null;
  try {
    // ethers v6 signature: wait(confirmations, timeoutMs)
    receipt = await response.wait(CONFIRMATIONS, RECEIPT_TIMEOUT_MS);
  } catch (e) {
    // A timeout is NOT proof of failure — the tx may still be pending.
    throw new TransactionFailedError(
      `Timed out waiting for a receipt for ${response.hash}. The transaction may still be pending; reconcile before retrying. (${
        e instanceof Error ? e.message : "unknown"
      })`,
      response.hash
    );
  }

  if (!receipt) {
    throw new TransactionFailedError(
      "No receipt returned. Outcome is uncertain — reconcile before retrying.",
      response.hash
    );
  }
  if (receipt.status !== 1) {
    throw new TransactionFailedError(
      `Transaction reverted on-chain (receipt status ${receipt.status}).`,
      response.hash
    );
  }

  return {
    txHash: response.hash,
    blockNumber: receipt.blockNumber,
    status: "confirmed",
    // A local chain settles immediately; this is the receipt's own count.
    confirmations: Number(receipt.confirmations ?? CONFIRMATIONS),
  };
}

function extractHash(e: unknown): string | null {
  if (e && typeof e === "object") {
    const maybe = e as { transactionHash?: string; hash?: string };
    return maybe.transactionHash ?? maybe.hash ?? null;
  }
  return null;
}

/** Turns ethers revert data into a readable message without leaking internals. */
export function describeError(e: unknown): string {
  if (e instanceof TransactionFailedError) return e.message;
  if (e instanceof BlockchainUnavailableError) return e.message;
  const err = e as { shortMessage?: string; reason?: string; message?: string; code?: string };
  if (err?.shortMessage) return err.shortMessage;
  if (err?.reason) return err.reason;
  if (err?.message) return err.message.split("\n")[0];
  if (err?.code === "ECONNREFUSED") return "Local blockchain is not running. Start it with: cd blockchain && npm run node";
  return "Blockchain operation failed";
}

/** Read-only batch state. Returns null when the batch is unknown on-chain. */
export async function readBatch(
  batchIdHash: string
): Promise<{ exists: boolean; metadataHash: string; registeredBy: string; registeredAt: number; active: boolean }> {
  const contract = getContract();
  const [registered, active] = (await contract.verifyBatch(batchIdHash)) as [boolean, boolean];
  if (!registered) {
    return { exists: false, metadataHash: ethers.ZeroHash, registeredBy: ethers.ZeroAddress, registeredAt: 0, active: false };
  }
  const b = (await contract.getBatch(batchIdHash)) as {
    metadataHash: string;
    registeredBy: string;
    registeredAt: bigint;
  };
  return {
    exists: true,
    metadataHash: b.metadataHash,
    registeredBy: b.registeredBy,
    registeredAt: Number(b.registeredAt),
    active,
  };
}

/** Resolves a pharmacy's local demo wallet address, or null if unmapped. */
export function pharmacyWallet(pharmacyId: number): string | null {
  const dep = loadDeployment();
  return dep?.accounts.pharmacies[String(pharmacyId)] ?? null;
}

export function deliveryWallet(index: number): string | null {
  const dep = loadDeployment();
  return dep?.accounts.delivery[String(index)] ?? null;
}

export function adminWallet(): string | null {
  return loadDeployment()?.accounts.admin ?? null;
}
